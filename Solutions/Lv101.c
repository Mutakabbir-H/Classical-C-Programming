// Q: Declare and print int, float, double and char variables using correct format specifiers.
#include<stdio.h>
int main()
{
    int a = 10;
    float b = 09.87;
    double c = 3.14159;
    char d = 'X';

    printf("%d\n",a);
    printf("%f\n",b);
    printf("%lf\n",c);
    printf("%c\n",d);

    return 0;

}